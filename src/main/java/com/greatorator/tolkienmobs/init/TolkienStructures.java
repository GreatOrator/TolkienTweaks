package com.greatorator.tolkienmobs.init;

import com.greatorator.tolkienmobs.world.components.structure.SurfaceStructures;
import com.greatorator.tolkienmobs.world.components.structure.TemplateLayoutStructure;
import com.greatorator.tolkienmobs.world.components.structure.VillageStructure;
import com.mojang.serialization.MapCodec;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructureType;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

import static com.greatorator.tolkienmobs.TolkienMobsMain.MODID;

public class TolkienStructures {
    // Configured structure keys; their JSON is generated by TolkienStructureProvider.
    public static final ResourceKey<Structure> HOBBIT_HOUSE = key("hobbit_house");
    // A traveller's camp: one tent, no connector, so it stands wherever the wilds allow it.
    public static final ResourceKey<Structure> WILD_TENT = key("wild_tent");
    public static final ResourceKey<Structure> SHIRE_RUIN = key("shire_ruin");
    public static final ResourceKey<Structure> CAVE = key("cave");
    public static final ResourceKey<Structure> MAZE = key("maze");

    public static final ResourceKey<Structure> BARROW = key("ttmbarrow");
    public static final ResourceKey<Structure> DARK_TOWER = key("ttmdark_tower");
    public static final ResourceKey<Structure> GOLLUM_CAVE = key("ttmgollum_cave");
    public static final ResourceKey<Structure> HOUSE_DESERT = key("ttmhouse_desert");
    public static final ResourceKey<Structure> HOUSE_NURN = key("ttmhouse_nurn");
    public static final ResourceKey<Structure> HOUSE_DWARF = key("ttmhouse_dwarf");
    public static final ResourceKey<Structure> HOUSE_ELVEN = key("ttmhouse_elven");
    public static final ResourceKey<Structure> HOUSE_HUMAN = key("ttmhouse_human");
    public static final ResourceKey<Structure> HOUSE_ORC = key("ttmhouse_orc");
    public static final ResourceKey<Structure> HOUSE_FROZEN = key("ttmhouse_frozen");
    // The six house keys above now generate complete villages; their IDs are retained for saves.
    public static final ResourceKey<Structure> INN_DESERT = key("ttminn_desert");
    public static final ResourceKey<Structure> RUIN_LARGE = key("ttmruin_large");
    public static final ResourceKey<Structure> RUIN_SMALL = key("ttmruin_small");
    public static final ResourceKey<Structure> SPIDERTREE = key("ttmtree_spider");
    public static final ResourceKey<Structure> SWAMP_HAG_HUT = key("ttmswamp_hag_hut");
    public static final ResourceKey<Structure> WARGPIT = key("ttmwargpit");

    public static ResourceKey<Structure> key(String name) {
        return ResourceKey.create(Registries.STRUCTURE, Identifier.fromNamespaceAndPath(MODID, name));
    }

    public static final DeferredRegister<StructureType<?>> STRUCTURE = DeferredRegister.create(Registries.STRUCTURE_TYPE, MODID);

    public static final DeferredHolder<StructureType<?>, StructureType<SurfaceStructures>> SURFACE_STRUCTURES = STRUCTURE.register("tolkien_surface_structures", () -> structureCodec(SurfaceStructures.CODEC));

    public static final DeferredHolder<StructureType<?>, StructureType<TemplateLayoutStructure>> TEMPLATE_LAYOUT =
            STRUCTURE.register("template_layout", () -> structureCodec(TemplateLayoutStructure.CODEC));

    /** Villages that may only start on grass instead of anywhere in their biome. */
    public static final DeferredHolder<StructureType<?>, StructureType<VillageStructure>> VILLAGE =
            STRUCTURE.register("village", () -> structureCodec(VillageStructure.CODEC));

    private static <T extends Structure> StructureType<T> structureCodec(MapCodec<T> structureCodec) {
        return () -> structureCodec;
    }
}
